-- Migration 019: Auto-close visits at end of day (mirror of shift auto-close)
-- Date: 2026-06-09
-- Purpose:
--   إضافة آلية إغلاق تلقائي للزيارات التي لم يُغلقها الطبيب يدوياً قبل
--   انتهاء اليوم/الفترة، تمامًا كما يحدث للورديات وتسديد الفواتير.
--
--   • العمود الجديد visits.auto_closed يميز الزيارات التي أغلقها النظام
--     تلقائياً (مماثل لـ shifts.auto_closed).
--   • الزيارة المُغلقة تلقائياً تحصل على:
--       diagnosis   = 'null'
--       final_notes = 'null'
--       closed_by   = 0   (المستخدم النظامي __system__)
--       closed_by_name = '__system__'
--       status      = 'Completed'
--       auto_closed = TRUE
--   • فهرس مساعد للاستعلام السريع عن الزيارات المُغلقة تلقائياً.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) عمود auto_closed في visits (آمن: IF NOT EXISTS)
-- ---------------------------------------------------------------------
ALTER TABLE visits
    ADD COLUMN IF NOT EXISTS auto_closed BOOLEAN NOT NULL DEFAULT FALSE;

-- ---------------------------------------------------------------------
-- 2) فهرس على الزيارات النشطة المربوطة بفترة (للإقفال التلقائي السريع)
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_visits_active_by_shift
    ON visits(shift_id)
    WHERE status = 'Active';

-- ---------------------------------------------------------------------
-- 3) فهرس مساعد للزيارات المُغلقة تلقائياً (للتقارير والتدقيق)
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_visits_auto_closed
    ON visits(auto_closed, closed_at DESC)
    WHERE auto_closed = TRUE;

